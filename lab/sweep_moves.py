"""Generate the move sweep: one single-monster roster per (species, up to 3 moves) and a test script that fights one
battle with each. Run with the hook's test sweep (testmode `sweep on`): every move is forced once per battle.

  python lab/sweep_moves.py <species.json> <save\\trainer dir> <out script> [first_slot] [k/n] [only species ids...]

k/n (e.g. 2/8): only every n-th roster, starting at the k-th, so n game copies can sweep in parallel.

Rosters go to slots 1000+ (real save keys are <= 0xEE). Prints one "slot species moves" line per roster.
"""
import json
import sys
from pathlib import Path

FIRST_SLOT = 1000

HEADER = """# generated by lab/sweep_moves.py: one battle per roster, every move forced once (hook test sweep), FFNx speed x4
log sweep
waitmode 27 30000
wait 2000
press ok
waitmode 20 30000
wait 2500
press up
wait 500
press ok
waitmode 1 30000
wait 4000
ffnx skip
wait 15000
press ok
wait 1500
press ok
wait 1500
sweep on
ffnx speedup
ffnx speedup
ffnx speedup
ffnx speedup
ffnx speedup
ffnx speedup
"""

BLOCK = """log SWEEP-BEGIN {slot}
core load {slot}
wait 300
fieldop 70 00 2C 01
waitmode 2 15000
whilemode 2 45000
press ok
wait 500
end
quitifmode 2
log SWEEP-END {slot}
whilemode 17 40000
press ok
wait 500
end
waitmode 1 20000
quitifnotmode 1
wait 1200
"""


def plan(species, only):
    out = []
    for sp in species:
        if sp["boss"] or (only and sp["id"] not in only):
            continue
        moves = sorted(int(m) for m in sp["moves"])
        for i in range(0, len(moves), 3):
            out.append((sp, moves[i:i + 3]))
    return out


def roster(slot, sp, moves):
    level = max(1, min(99, sp.get("native_level", 10)))
    mon = {"uid": 1, "species": sp["id"], "nickname": sp["name"].replace("?", "-")[:16], "level": level,
           "xp": 0 if level <= 1 else int(level ** 3.2), "hp": 1, "mp": 999, "known": moves, "equipped": moves,
           "caught_level": level, "caught_scene": 0}
    return {"version": 1, "slot": slot, "roster": {"next_uid": 2, "party": [mon], "box": [],
            "trainer": {"captures": 1, "battles": 0, "legendary_unlocked": False, "kit_given": True}}}


def main():
    species = json.loads(Path(sys.argv[1]).read_text(encoding="utf-8"))["species"]
    save_dir, script = Path(sys.argv[2]), Path(sys.argv[3])
    first = int(sys.argv[4]) if len(sys.argv) > 4 else FIRST_SLOT
    rest = sys.argv[5:]
    shard, shards = 0, 1
    if rest and "/" in rest[0]:
        shard, shards = map(int, rest.pop(0).split("/"))
    only = {int(a) for a in rest}
    body = [HEADER]
    for n, (sp, moves) in enumerate(plan(species, only)):
        slot = FIRST_SLOT + n
        if slot < first or n % shards != shard:
            continue
        (save_dir / f"trainer_slot{slot:02}.json").write_text(json.dumps(roster(slot, sp, moves), indent=1))
        body.append(BLOCK.format(slot=slot))
        print(slot, sp["id"], " ".join(map(str, moves)))
    body.append("log SWEEP-ALL-DONE\nquit\n")
    script.write_text("".join(body))


if __name__ == "__main__":
    main()
